from typing import Any, TypedDict


class Text2SQLState(TypedDict, total=False):
    """Text2SQL LangGraph共享状态。

    每个节点只返回自己修改的字段，LangGraph会将更新合并到状态中。
    """

    # ==================================================
    # 用户输入
    # ==================================================

    question: str

    # ==================================================
    # Schema
    # ==================================================

    schema_context: str

    # ==================================================
    # SQL生成与修复
    # ==================================================

    # 第一次由generate_sql生成的SQL，用于调试和展示
    initial_sql: str

    # 当前准备校验的SQL
    # 修复后会被新的SQL覆盖
    raw_sql: str

    # 已经通过SQL Guard检查的SQL
    validated_sql: str

    # 当前已经执行过多少次自动修复
    retry_count: int

    # 最近一次触发修复的错误
    last_repair_reason: str

    # ==================================================
    # 错误信息
    # ==================================================

    validation_error: str
    execution_error: str

    # ==================================================
    # 查询结果
    # ==================================================

    columns: list[str]
    rows: list[list[Any]]
    row_count: int
    truncated: bool

    # ==================================================
    # 最终返回
    # ==================================================

    final_answer: str